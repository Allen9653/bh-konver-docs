const replaceCharacters = (text: string, pairs: Array<[string, string]>) => {
  let result = text;
  for (const [source, target] of pairs) result = result.split(source).join(target);
  return result;
};

export const latinToCyrillic = (text: string) => replaceCharacters(text, LATIN_TO_CYRILLIC);
export const cyrillicToLatin = (text: string) => replaceCharacters(text, CYRILLIC_TO_LATIN);